import { _electron as electron } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import http from 'node:http';
import { generateKeyPairSync, sign } from 'node:crypto';
import { createRoomServer } from '../server/index.mjs';

assert.equal(process.platform, 'win32', 'Run this smoke test on a real Windows runner');
assert.ok(process.env.CORNER_EXECUTABLE, 'CORNER_EXECUTABLE must point to the NSIS-installed app');
const executablePath = path.resolve(process.env.CORNER_EXECUTABLE);
await fs.access(executablePath);
const version = JSON.parse(await fs.readFile(new URL('../package.json', import.meta.url), 'utf8')).version;
const results = path.resolve('test-results');
await fs.mkdir(results, { recursive: true });
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'corner-windows-smoke-'));
const userData = path.join(temporary, 'profile');
const updateConfig = path.join(temporary, 'update-config.json');
const keys = generateKeyPairSync('ed25519');
let envelope;
const feed = http.createServer((request, response) => {
  if (request.url !== '/win-latest.json') { response.writeHead(404); response.end(); return; }
  response.writeHead(200, { 'Content-Type': 'application/json' });
  response.end(JSON.stringify(envelope));
});
const relay = createRoomServer();
let application;
const errors = [];
try {
  await relay.listen(0, '127.0.0.1');
  await new Promise((resolve, reject) => { feed.once('error', reject); feed.listen(0, '127.0.0.1', resolve); });
  const serverUrl = `http://127.0.0.1:${relay.httpServer.address().port}`;
  const feedUrl = `http://127.0.0.1:${feed.address().port}/win-latest.json`;
  const payload = Buffer.from(JSON.stringify({ schema: 1, appId: 'com.corner.chiikawa', platform: 'win32', arch: 'x64', version, url: `http://127.0.0.1:${feed.address().port}/update.exe`, size: 1, sha256: 'a'.repeat(64), releaseNotes: 'Windows 설치형 앱 업데이트 확인 검증' }));
  envelope = { payload: payload.toString('base64'), signature: sign(null, payload, keys.privateKey).toString('base64') };
  await fs.writeFile(updateConfig, JSON.stringify({ winFeedUrl: feedUrl, feedUrl, publicKey: keys.publicKey.export({ type: 'spki', format: 'pem' }) }));
  const env = { ...process.env, CORNER_TEST: '1', CORNER_USER_DATA: userData, CORNER_SERVER_URL: serverUrl, CORNER_UPDATE_CONFIG: updateConfig };
  delete env.ELECTRON_RUN_AS_NODE;
  delete env.CORNER_DEV_URL;
  delete env.CORNER_HEADLESS;
  application = await electron.launch({ executablePath, args: [], env, timeout: 60000 });
  let panel;
  for (let i = 0; i < 150; i++) {
    panel = application.windows().find((page) => page.url().includes('view=panel'));
    if (panel) break;
    await new Promise((resolve) => setTimeout(resolve, 100));
  }
  assert.ok(panel, 'Installed Windows panel must open');
  panel.on('pageerror', (error) => errors.push(error.message));
  panel.setDefaultTimeout(30000);
  await panel.locator('.app-shell').waitFor();
  const config = await panel.evaluate(() => window.corner.getConfig());
  assert.equal(config.platform, 'win32');
  assert.equal(config.version, version);
  assert.equal(config.isDesktop, true);
  await panel.locator('.status-pill.online').waitFor();
  await panel.locator('#nickname').fill('윈도우검증');
  await panel.locator('.character-option').nth(1).click();
  await panel.screenshot({ path: path.join(results, 'windows-onboarding.png') });
  await panel.getByRole('button', { name: '우리 방 만들기', exact: true }).click();
  await panel.locator('.room-code').waitFor();
  const overlay = application.windows().find((page) => page.url().includes('view=overlay'));
  assert.ok(overlay, 'The Windows desktop overlay must exist');
  overlay.on('pageerror', (error) => errors.push(error.message));
  await overlay.locator('.desktop-pet').waitFor();
  assert.equal(await overlay.locator('.desktop-pet').count(), 1);
  const overlayState = await application.evaluate(({ BrowserWindow }) => {
    const window = BrowserWindow.getAllWindows().find((item) => item.webContents.getURL().includes('view=overlay'));
    return { visible: window.isVisible(), focusable: window.isFocusable(), onTop: window.isAlwaysOnTop(), bounds: window.getBounds() };
  });
  assert.equal(overlayState.visible, true);
  assert.equal(overlayState.focusable, false);
  assert.equal(overlayState.onTop, true);
  assert.equal(await overlay.evaluate(() => getComputedStyle(document.body).backgroundColor), 'rgba(0, 0, 0, 0)');
  const message = '윈도우에서도 친구들과 말풍선으로 만나!';
  await panel.getByRole('textbox', { name: '친구에게 보낼 말' }).fill(message);
  await panel.getByRole('button', { name: '메시지 보내기' }).click();
  await overlay.getByText(message, { exact: true }).waitFor();
  await panel.screenshot({ path: path.join(results, 'windows-room.png') });
  await overlay.screenshot({ path: path.join(results, 'windows-overlay.png'), omitBackground: true });
  await panel.getByRole('button', { name: '창 접고 바탕화면에서 만나기' }).click();
  assert.equal(await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((item) => item.webContents.getURL().includes('view=panel')).isVisible()), false);
  await overlay.evaluate(() => window.corner.openPanel());
  await panel.waitForFunction(() => document.visibilityState === 'visible');
  assert.equal((await panel.evaluate(() => window.corner.getUpdateState())).phase, 'idle');
  await panel.getByRole('button', { name: '업데이트', exact: true }).click();
  await panel.getByRole('button', { name: '업데이트 확인', exact: true }).click();
  await panel.getByRole('heading', { name: '지금 최신 버전이야', exact: true }).waitFor();
  assert.equal((await panel.evaluate(() => window.corner.getUpdateState())).latestVersion, version);
  await panel.screenshot({ path: path.join(results, 'windows-update.png') });
  await panel.getByRole('button', { name: '업데이트 창 닫기' }).click();
  await panel.reload();
  await panel.locator('.room-code').waitFor();
  await panel.locator('.message-list').getByText(message, { exact: true }).waitFor();
  const profile = await panel.evaluate(() => JSON.parse(localStorage.getItem('corner.profile')));
  assert.equal(profile.nickname, '윈도우검증');
  assert.equal(profile.character, 'hachiware');
  await panel.getByRole('button', { name: '나가기', exact: true }).click();
  await panel.locator('#nickname').waitFor();
  assert.equal(await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find((item) => item.webContents.getURL().includes('view=overlay')).isVisible()), false);
  assert.deepEqual(errors, []);
  const report = { ok: true, platform: process.platform, arch: process.arch, version, checks: ['NSIS-installed native startup', 'bundled character assets', 'live room and chat', 'transparent non-focusable topmost overlay', 'desktop speech bubble', 'hide/reopen panel', 'signed Windows update check', 'profile and room reload persistence', 'leave hides overlay'], overlayState };
  await fs.writeFile(path.join(results, 'windows-smoke.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally {
  if (application) await application.close().catch(() => {});
  feed.closeAllConnections();
  await new Promise((resolve) => feed.close(resolve));
  await relay.close();
  await fs.rm(temporary, { recursive: true, force: true, maxRetries: 5, retryDelay: 400 });
}
